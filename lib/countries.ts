export function getCountryByIso(iso2: string): CountryCode {
  return countries.find((country) => country.iso2 === iso2) ?? countries[0];
}

export function detectCountryFromInternationalNumber(
  value: string
): CountryCode | null {
  const digits = value.replace(/[^\d+]/g, "").replace(/^\+/, "");
  if (!digits) {
    return null;
  }

  return (
    [...countries]
      .sort((a, b) => b.dialCode.length - a.dialCode.length)
      .find((country) => digits.startsWith(country.dialCode)) ?? null
  );
}
